import { formatDuration, formatTimestamp } from "@/lib/format";
import type { AnalysisResult, Finding, ReviewReport } from "@/lib/types";
import { designationLabel, statusLabel, uncertaintyLabel } from "./findingStyles";

interface PrintableReviewProps {
  sessionName: string;
  fileName: string;
  durationSec: number;
  source: AnalysisResult["source"];
  findings: Finding[];
  report: ReviewReport | null;
  reportStale: boolean;
}

/**
 * The document behind "Export review PDF". Hidden on screen; when printing it is the only
 * thing shown (the workspace is print:hidden), so "Save as PDF" produces a clean report.
 * Everything is plain text from validated data.
 */
export function PrintableReview({
  sessionName,
  fileName,
  durationSec,
  source,
  findings,
  report,
  reportStale,
}: PrintableReviewProps) {
  const count = (s: Finding["reviewStatus"]) => findings.filter((f) => f.reviewStatus === s).length;
  const stats = [
    ["Findings", findings.length],
    ["Confirmed", count("confirmed")],
    ["Still to review", count("needs_review")],
    ["Dismissed", count("dismissed")],
  ] as const;

  return (
    <div className="hidden text-[11pt] leading-snug text-black print:block">
      <header className="border-b border-black pb-3">
        <p className="eyebrow">reScrub · Sterile-technique review</p>
        <h1 className="font-display mt-1 text-[22pt] leading-tight">{sessionName}</h1>
        <p className="mt-1 text-[9.5pt]">
          {fileName} · {formatDuration(durationSec)} · Exported {new Date().toLocaleString()}
        </p>
        {source === "demo" && (
          <p className="mt-1 text-[9.5pt] font-semibold">
            Demonstration data on a synthetic clip. This is not a review of a real procedure.
          </p>
        )}
      </header>

      <table className="mt-3 w-full border-collapse text-[10pt]">
        <tbody>
          <tr>
            {stats.map(([label, value]) => (
              <td key={label} className="border border-black/40 px-2 py-1">
                <span className="block text-[8pt] uppercase tracking-wide">{label}</span>
                <span className="text-[14pt]">{value}</span>
              </td>
            ))}
          </tr>
        </tbody>
      </table>

      <section className="mt-5 break-inside-avoid">
        <h2 className="text-[13pt] font-semibold">Final report</h2>
        {report ? (
          <>
            <p className="mt-1 text-[9pt] italic">
              {report.source === "demo"
                ? "Hand-written sample for the demonstration (not generated by Gemini)."
                : `Written by ${report.model}${report.generatedAt ? ` on ${new Date(report.generatedAt).toLocaleString()}` : ""} from the findings and reviewer decisions.`}
              {reportStale && " Reviewer decisions changed after it was written; the findings table below is current."}
            </p>
            <p className="mt-2">{report.overview}</p>
            {report.keyMoments.length > 0 && (
              <>
                <h3 className="mt-3 font-semibold">Key moments</h3>
                <ol className="mt-1 space-y-1.5">
                  {report.keyMoments.map((m) => (
                    <li key={m.eventId} className="break-inside-avoid">
                      <span className="font-mono">{formatTimestamp(m.timestampSec)}</span> · <strong>{m.title}</strong> ·{" "}
                      {statusLabel[m.reviewStatus]}
                      <br />
                      {m.summary}
                      {m.teachingPoint && <> Practice: {m.teachingPoint}</>}
                    </li>
                  ))}
                </ol>
              </>
            )}
            {report.coachingPoints.length > 0 && (
              <>
                <h3 className="mt-3 font-semibold">What to practice</h3>
                <ol className="mt-1 list-decimal pl-5">
                  {report.coachingPoints.map((p) => (
                    <li key={p}>{p}</li>
                  ))}
                </ol>
              </>
            )}
            {report.limitations && <p className="mt-3 text-[9.5pt]">Limits: {report.limitations}</p>}
          </>
        ) : (
          <p className="mt-1 text-[10pt]">No final report was written for this session.</p>
        )}
      </section>

      <section className="mt-5">
        <h2 className="text-[13pt] font-semibold">All findings and decisions</h2>
        {findings.length === 0 ? (
          <p className="mt-1">No moments were flagged. That does not prove the technique was flawless.</p>
        ) : (
          <table className="mt-2 w-full border-collapse text-[9.5pt]">
            <thead>
              <tr className="text-left">
                <th className="border-b border-black py-1 pr-2">Time</th>
                <th className="border-b border-black py-1 pr-2">Finding</th>
                <th className="border-b border-black py-1 pr-2">Decision</th>
                <th className="border-b border-black py-1">Certainty</th>
              </tr>
            </thead>
            <tbody>
              {findings.map((f) => (
                <tr key={f.eventId} className="break-inside-avoid align-top">
                  <td className="border-b border-black/30 py-1.5 pr-2 font-mono">{formatTimestamp(f.timestampSec)}</td>
                  <td className="border-b border-black/30 py-1.5 pr-2">
                    <strong>{f.title}</strong>
                    <br />
                    {f.description}
                    {f.evidence.length > 0 && (
                      <span className="mt-0.5 block text-[8.5pt]">
                        {f.evidence
                          .map((e) => `${formatTimestamp(e.timestampSec)} ${e.label} (${designationLabel[e.designation]})`)
                          .join(" → ")}
                      </span>
                    )}
                  </td>
                  <td className="border-b border-black/30 py-1.5 pr-2">{statusLabel[f.reviewStatus]}</td>
                  <td className="border-b border-black/30 py-1.5">{uncertaintyLabel[f.uncertainty.level]}</td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </section>

      <footer className="mt-6 border-t border-black pt-2 text-[8.5pt]">
        reScrub is a training tool. Findings are automated suggestions that a person reviewed; they do not detect
        microbes, certify sterility, or establish that contamination occurred.
      </footer>
    </div>
  );
}
