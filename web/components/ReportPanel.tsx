"use client";

import { formatTimestamp } from "@/lib/format";
import type { ReviewReport } from "@/lib/types";
import { statusChip, statusDot, statusLabel, uncertaintyLabel } from "./findingStyles";
import { buttonStyles, chip } from "./ui";

export type ReportStatus = "idle" | "loading" | "writing" | "error";

interface ReportPanelProps {
  report: ReviewReport | null;
  /** "demo" shows a hand-written sample; "backend" asks the server to write one with Gemini. */
  source: "demo" | "backend";
  status: ReportStatus;
  error: string | null;
  /** Reviewer decisions changed since the report was written. */
  stale: boolean;
  onWrite: () => void;
  onJump: (eventId: string) => void;
}

/**
 * The final review report. Its text comes from an AI model (or the demo sample), so it is
 * shown as plain text only, every moment links back to a real finding, and the panel says
 * clearly who wrote it and that a person makes the decisions.
 */
export function ReportPanel({ report, source, status, error, stale, onWrite, onJump }: ReportPanelProps) {
  const busy = status === "writing" || status === "loading";
  const writeLabel = source === "demo" ? "Show sample report" : report ? "Rewrite report" : "Write report with Gemini";

  return (
    <section aria-labelledby="report-heading" className="rounded-[3px] border border-line bg-surface">
      <div className="flex flex-col gap-3 border-b border-line px-4 py-3.5 sm:flex-row sm:items-start sm:justify-between">
        <div>
          <h2 id="report-heading" className="eyebrow text-ink">
            Final report
          </h2>
          <p className="mt-1 text-[13px] text-ink-muted">
            {source === "demo"
              ? "A hand-written sample for the demonstration. It was not generated by Gemini."
              : "Written by Google Gemini from the findings and your decisions. The video is never sent."}
          </p>
        </div>
        {(!report || stale || source === "backend") && (
          <button
            type="button"
            className={`${report ? buttonStyles.secondary : buttonStyles.primary} shrink-0`}
            onClick={onWrite}
            disabled={busy}
          >
            {status === "writing" ? "Writing…" : status === "loading" ? "Loading…" : writeLabel}
          </button>
        )}
      </div>

      <div className="px-4 py-4" aria-live="polite" aria-busy={busy}>
        {status === "writing" && (
          <div className="mb-4">
            <p className="text-sm text-ink-muted">Gemini is writing the report. This usually takes under a minute.</p>
            <div className="mt-2 h-[3px] overflow-hidden bg-line" aria-hidden="true">
              <div className="indeterminate h-full w-2/5 bg-accent" />
            </div>
          </div>
        )}

        {error && (
          <p role="alert" className="mb-4 border-l-2 border-flag-mark bg-flag-soft px-3 py-2 text-sm text-flag">
            {error}
          </p>
        )}

        {report && stale && (
          <p className="mb-4 border-l-2 border-amber-mark bg-amber-soft px-3 py-2 text-sm text-amber">
            Your decisions changed after this report was written. Rewrite it so it matches.
          </p>
        )}

        {!report && status !== "writing" && !error && (
          <p className="text-sm text-ink-muted">
            {source === "demo"
              ? "See what a final report looks like for this demonstration."
              : "Review the findings first, then write a report that summarizes the session, highlights the moments that matter, and suggests what to practice. It sends finding text and your decisions to Google Gemini; the video, file name and session name are not sent."}
          </p>
        )}

        {report && (
          <article className="space-y-5 text-[15px] leading-relaxed">
            <p className="font-display text-[20px] leading-snug tracking-[-0.005em]">{report.overview}</p>

            {report.keyMoments.length > 0 && (
              <div>
                <h3 className="eyebrow text-ink-faint">Key moments</h3>
                <ol className="mt-2 divide-y divide-line border-y border-line">
                  {report.keyMoments.map((m) => (
                    <li key={m.eventId} className="py-3">
                      <div className="flex flex-wrap items-center gap-2">
                        <button
                          type="button"
                          onClick={() => onJump(m.eventId)}
                          className="tabular rounded-[2px] font-mono text-[13px] text-accent underline-offset-4 hover:underline"
                          aria-label={`Watch ${m.title} at ${formatTimestamp(m.timestampSec)}`}
                        >
                          {formatTimestamp(m.timestampSec)}
                        </button>
                        <span className="font-semibold">{m.title}</span>
                        <span className={`${chip} ${statusChip[m.reviewStatus]}`}>
                          <span className={`size-1.5 rounded-full ${statusDot[m.reviewStatus]}`} aria-hidden="true" />
                          {statusLabel[m.reviewStatus]}
                        </span>
                        {m.uncertainty !== "low" && (
                          <span className={`${chip} bg-amber-soft text-amber`}>{uncertaintyLabel[m.uncertainty]}</span>
                        )}
                      </div>
                      <p className="mt-1">{m.summary}</p>
                      {m.teachingPoint && (
                        <p className="mt-1 text-ink-muted">
                          <span className="font-medium text-ink">Practice: </span>
                          {m.teachingPoint}
                        </p>
                      )}
                    </li>
                  ))}
                </ol>
              </div>
            )}

            {report.coachingPoints.length > 0 && (
              <div>
                <h3 className="eyebrow text-ink-faint">What to practice</h3>
                <ol className="mt-2 list-decimal space-y-1 pl-5">
                  {report.coachingPoints.map((p) => (
                    <li key={p}>{p}</li>
                  ))}
                </ol>
              </div>
            )}

            {report.limitations && (
              <div>
                <h3 className="eyebrow text-ink-faint">Limits of this review</h3>
                <p className="mt-1 text-ink-muted">{report.limitations}</p>
              </div>
            )}

            <p className="border-t border-line pt-3 text-[13px] text-ink-muted">
              {report.source === "demo" ? "Sample text for the demonstration" : `Written by ${report.model}`}
              {report.generatedAt && report.source !== "demo" && <> · {new Date(report.generatedAt).toLocaleString()}</>}
              . A training aid, not a clinical determination. An instructor makes every decision.
            </p>
          </article>
        )}
      </div>
    </section>
  );
}
